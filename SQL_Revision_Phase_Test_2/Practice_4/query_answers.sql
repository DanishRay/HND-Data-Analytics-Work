-- Question a
-- Write a query to calculate the average transaction amount spent by customers partitioned by the customer city
SELECT t.transaction_id, c.city, t.total_amount,
AVG(t.total_amount) OVER(PARTITION BY c.city) AS city_avg_spend
FROM transactions t
JOIN customers c ON t.customer_id = c.customer_id;
-- This operation combines a JOIN to get the CITY name with an AVG() OVER()
-- to calculate the regional averages.



-- Question b
-- Write a query to find the names of all products that have never been sold
SELECT product_id, product_name
FROM products
WHERE product_id NOT IN(
	SELECT product_id
	FROM transaction_items
)
ORDER BY product_id;
-- The NOT IN operator compares the PRODUCT_ID against a list generated by the subquery.
-- This is the standard way to find missing records between to related tables




-- Question c
-- Write a query to list all transactions including the email of the customer who made them
SELECT t.transaction_id, t.transaction_date, c.email
FROM transactions t
JOIN customers c ON t.customer_id = c.customer_id;
-- A JOIN used to pull related attributes from a separate table using the CUSTOMER_ID foreign key



-- Question d
-- Write a query to categorize products based on their price
SELECT product_name, price,
	CASE
		WHEN price > 10.00 THEN 'Premium'
		WHEN price BETWEEN 5.00 AND 10.00 THEN 'Mid-Range'
		WHEN price < 5.00 THEN 'Budget'
		ELSE 'Unpriced'
	END AS price_tier
FROM products;
-- This uses BETWEEN and comparison operators (>,<) to bucket numerical data into categorical



-- Question e
-- Write a query to find the maximum stock quantity available within each product category
SELECT category,
MIN(stock_quantity) AS minimum_stock,
MAX(stock_quantity) AS maximum_stock
FROM products
GROUP BY category;
-- GROUP BY collapse all individual products into a single row per category
-- MIN(), MAX() functions find the extreme values within those collapsed groups
